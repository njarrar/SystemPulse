#!/usr/bin/env node
// Writes Tests/PulseCoreTests/Fixtures/cldr-intl.json: plural categories from
// Intl.PluralRules (ICU's CLDR data) for languages Pulse may add, used to
// check the Swift plural port. Run with Node 18 or later.
'use strict';
const fs = require('fs');
const path = require('path');
// CLDR rules, copied from i18n/test/test.js.
const RULES = {
  en: { one: 'i = 1 and v = 0' },
  ar: { zero: 'n = 0', one: 'n = 1', two: 'n = 2', few: 'n % 100 = 3..10', many: 'n % 100 = 11..99' },
  he: { one: 'i = 1 and v = 0 or i = 0 and v != 0', two: 'i = 2 and v = 0' },
  ru: { one: 'v = 0 and i % 10 = 1 and i % 100 != 11', few: 'v = 0 and i % 10 = 2..4 and i % 100 != 12..14', many: 'v = 0 and i % 10 = 0 or v = 0 and i % 10 = 5..9 or v = 0 and i % 100 = 11..14' },
  pl: { one: 'i = 1 and v = 0', few: 'v = 0 and i % 10 = 2..4 and i % 100 != 12..14', many: 'v = 0 and i != 1 and i % 10 = 0..1 or v = 0 and i % 10 = 5..9 or v = 0 and i % 100 = 12..14' },
  cy: { zero: 'n = 0', one: 'n = 1', two: 'n = 2', few: 'n = 3', many: 'n = 6' },
  fr: { one: 'i = 0,1', many: 'e = 0 and i != 0 and i % 1000000 = 0 and v = 0 or e != 0..5' },
  lv: { zero: 'n % 10 = 0 or n % 100 = 11..19 or v = 2 and f % 100 = 11..19', one: 'n % 10 = 1 and n % 100 != 11 or v = 2 and f % 10 = 1 and f % 100 != 11 or v != 2 and f % 10 = 1' },
  fa: { one: 'i = 0 or n = 1' },
  ja: {}
};
const LETTER = { zero: 'z', one: 'o', two: 't', few: 'f', many: 'm', other: 'x' };
const out = { note: 'Generated by scripts/make-cldr-fixture.js from Intl.PluralRules. Letters: z zero, o one, t two, f few, m many, x other.', icu: process.versions.icu, languages: {} };
for (const [code, rules] of Object.entries(RULES)) {
  const row = { rules };
  for (let d = 0; d <= 2; d++) {
    const max = d ? 30 : 1200, step = d ? 0.01 : 1;
    const pr = new Intl.PluralRules(code, { minimumFractionDigits: d, maximumFractionDigits: d });
    let s = '';
    for (let k = 0; k * step <= max + 1e-9; k++) s += LETTER[pr.select(+(k * step).toFixed(d))];
    row['d' + d] = s;
  }
  out.languages[code] = row;
}
const file = path.join(__dirname, '..', 'Tests', 'PulseCoreTests', 'Fixtures', 'cldr-intl.json');
fs.writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
console.log('wrote ' + file);
