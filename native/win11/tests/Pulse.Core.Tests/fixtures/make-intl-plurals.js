#!/usr/bin/env node
// Writes intl-plurals.json: Intl.PluralRules categories for the languages the
// JS engine test covers, so the C# port can be checked without a JS runtime.
// Each series is one letter per value: z one t(wo) f(ew) m(any) o(ther) -> z,1,2,f,m,o.
// Run: node make-intl-plurals.js > intl-plurals.json
'use strict';
const RULES = {
  en: { one: 'i = 1 and v = 0' },
  ar: { zero: 'n = 0', one: 'n = 1', two: 'n = 2', few: 'n % 100 = 3..10', many: 'n % 100 = 11..99' },
  he: { one: 'i = 1 and v = 0 or i = 0 and v != 0', two: 'i = 2 and v = 0' },
  ru: { one: 'v = 0 and i % 10 = 1 and i % 100 != 11', few: 'v = 0 and i % 10 = 2..4 and i % 100 != 12..14', many: 'v = 0 and i % 10 = 0 or v = 0 and i % 10 = 5..9 or v = 0 and i % 100 = 11..14' },
  pl: { one: 'i = 1 and v = 0', few: 'v = 0 and i % 10 = 2..4 and i % 100 != 12..14', many: 'v = 0 and i != 1 and i % 10 = 0..1 or v = 0 and i % 10 = 5..9 or v = 0 and i % 100 = 12..14' },
  cy: { zero: 'n = 0', one: 'n = 1', two: 'n = 2', few: 'n = 3', many: 'n = 6' },
  fr: { one: 'i = 0,1', many: 'e = 0 and i != 0 and i % 1000000 = 0 and v = 0 or e != 0..5' },
  lv: { zero: 'n % 10 = 0 or n % 100 = 11..19 or v = 2 and f % 100 = 11..19', one: 'n % 10 = 1 and n % 100 != 11 or v = 2 and f % 10 = 1 and f % 100 != 11 or v != 2 and f % 10 = 1' },
  fa: { one: 'i = 0 or n = 1' },
  ja: {}
};
const L = { zero: 'z', one: '1', two: '2', few: 'f', many: 'm', other: 'o' };
const out = { note: 'Generated by make-intl-plurals.js from Intl.PluralRules (Node ' + process.version + ').', languages: {} };
for (const [code, rules] of Object.entries(RULES)) {
  const series = {};
  for (let d = 0; d <= 2; d++) {
    const max = d ? 30 : 1200, step = d ? Math.pow(10, -d) : 1;
    const pr = new Intl.PluralRules(code, { minimumFractionDigits: d, maximumFractionDigits: d });
    let s = '';
    for (let k = 0; k * step <= max + 1e-9; k++) s += L[pr.select(+(k * step).toFixed(d))];
    series[d] = { max, step, cats: s };
  }
  out.languages[code] = { rules, series };
}
process.stdout.write(JSON.stringify(out, null, 1) + '\n');
